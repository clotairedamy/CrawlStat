/**
 * Regenerates `engine/tests/fixtures/node_signed_token.json`.
 *
 * That fixture is how the two halves of the licence contract are kept honest:
 * this file signs a token exactly as the API does, and a Rust test verifies it
 * with the engine's own verifier. If either side changes its encoding — the
 * base64 alphabet, the field names, what the signature covers — the Rust test
 * fails, rather than every customer's activation failing in production.
 *
 *   cd site && npx tsx test/make-fixture.ts
 */
import { generateKeyPairSync } from 'node:crypto'
import { writeFileSync } from 'node:fs'

import { buildEntitlement, publicKeyHex, signEntitlement } from '../server/utils/token'

const { privateKey } = generateKeyPairSync('ed25519')
const pem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString()

const entitlement = buildEntitlement({
  plan: 'pro',
  licenseKey: 'CS-FIXTURE-0001',
  instanceId: 'fixture-instance',
  now: 1_800_000_000,
})

writeFileSync(
  '../engine/tests/fixtures/node_signed_token.json',
  `${JSON.stringify(
    {
      _comment:
        'Generated by site/test/make-fixture.ts with node:crypto. Proves the Node signing ' +
        'format and the Rust verifier agree. Regenerate with: cd site && npx tsx test/make-fixture.ts',
      publicKeyHex: publicKeyHex(pem),
      token: signEntitlement(entitlement, pem),
      expected: entitlement,
    },
    null,
    2,
  )}\n`,
)

console.log('fixture written')
